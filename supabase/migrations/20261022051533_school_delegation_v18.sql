begin;
create schema if not exists hr_private;
revoke all on schema hr_private from public,anon;
grant usage on schema hr_private to authenticated,service_role;
alter table public.schools drop constraint if exists schools_id_check;
do $$begin
 if not exists(select 1 from information_schema.columns where table_schema='public' and table_name='schools' and column_name='id' and is_identity='YES') then
  alter table public.schools alter column id add generated by default as identity;
 end if;
 perform setval(pg_get_serial_sequence('public.schools','id'),greatest(coalesce((select max(id) from public.schools),0),1),(select count(*)>0 from public.schools));
end $$;
create unique index if not exists schools_name_unique on public.schools(lower(btrim(name)));
alter table public.schools add column if not exists is_active boolean not null default true;
alter table public.schools add column if not exists revision integer not null default 1;
alter table public.profiles drop constraint if exists profiles_role_check;
alter table public.profiles add constraint profiles_role_check check(role in ('admin','personnel','school_editor'));
create table if not exists public.school_assignments(
 id uuid primary key default gen_random_uuid(),user_id uuid not null references public.profiles(id),
 school_id integer not null references public.schools(id),
 permissions text[] not null default array['view'],personnel_ids uuid[],
 revision integer not null default 1,updated_at timestamptz not null default now(),
 unique(user_id,school_id),
 check(permissions @> array['view'] and permissions <@ array['view','create_personnel','personnel_write','education_write','certificates_write','documents_write','import','request_delete']),
 check(personnel_ids is null or cardinality(personnel_ids)>0)
);
create index if not exists school_assignments_school_idx on public.school_assignments(school_id);
create table if not exists public.administration_changes(
 id uuid primary key default gen_random_uuid(),entity text not null,record_id text not null,
 action text not null,old_data jsonb not null default '{}',new_data jsonb not null default '{}',
 reason text not null,actor_id uuid not null,created_at timestamptz not null default now()
);
alter table public.school_assignments enable row level security;
alter table public.administration_changes enable row level security;
drop policy if exists assignments_read on public.school_assignments;
create policy assignments_read on public.school_assignments for select to authenticated using(public.account_ready() and (public.is_admin() or user_id=(select auth.uid())));
drop policy if exists administration_read on public.administration_changes;
create policy administration_read on public.administration_changes for select to authenticated using(public.is_admin());
revoke all on public.school_assignments,public.administration_changes from public,anon,authenticated;
grant select on public.school_assignments,public.administration_changes to authenticated;
grant all on public.school_assignments,public.administration_changes to service_role;
-- School writes go exclusively through the revision-checked RPC.
revoke insert,update,delete on public.schools from authenticated;

create or replace function hr_private.school_permission(actor uuid,target_school integer,permission text,target_person uuid default null)
returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.school_assignments a join public.profiles u on u.id=a.user_id
 join public.schools s on s.id=a.school_id where a.user_id=actor and a.school_id=target_school
 and u.role='school_editor' and u.account_enabled and not u.account_pending and not u.must_change_password
 and permission=any(a.permissions) and (permission='view' or s.is_active)
 and (a.personnel_ids is null or (target_person is not null and target_person=any(a.personnel_ids))));
$$;
create or replace function hr_private.personnel_allowed(actor uuid,target_person uuid,permission text)
returns boolean language sql stable security definer set search_path='' as $$
 select exists(select 1 from public.personnel p join public.profiles u on u.id=actor join public.schools s on s.id=p.school_id
 where p.id=target_person and u.account_enabled and not u.account_pending and not u.must_change_password
 and (u.role='admin' or (p.deleted_at is null and (
  (p.user_id=actor and (permission='view' or (s.is_active and permission=any(array['contact_write','documents_write','request_delete']))))
  or hr_private.school_permission(actor,p.school_id,permission,p.id)))));
$$;
create or replace function hr_private.school_access(target_school integer,permission text)
returns boolean language sql stable security definer set search_path='' as $$
 select public.account_ready() and hr_private.school_permission(auth.uid(),target_school,permission);
$$;
-- No arbitrary actor can be supplied to this client-callable helper.
create or replace function hr_private.personnel_access(target_person uuid,permission text)
returns boolean language sql stable security definer set search_path='' as $$
 select public.account_ready() and permission=any(array['view','contact_write','personnel_write','education_write','certificates_write','documents_write','request_delete'])
 and hr_private.personnel_allowed(auth.uid(),target_person,permission);
$$;
create or replace function public.hr_personnel_access(personnel_id uuid,permission text default 'view')
returns boolean language sql stable security invoker set search_path='' as $$
 select hr_private.personnel_access(personnel_id,permission);
$$;

create or replace function hr_private.school_manage(operation text,school_data jsonb,expected_revision integer,reason text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare current_row public.schools; next_row public.schools; result jsonb;
begin
 if not public.is_admin() then raise exception 'เฉพาะผู้ดูแลระบบ' using errcode='42501';end if;
 if reason is null or length(trim(reason)) not between 5 and 1000 then raise exception 'กรุณาระบุเหตุผล 5–1,000 ตัวอักษร';end if;
 if operation not in ('create','update','deactivate','activate','delete') or operation is null then raise exception 'คำสั่งไม่ถูกต้อง';end if;
 if jsonb_typeof(school_data) is distinct from 'object' or exists(select 1 from jsonb_object_keys(school_data) k where k not in ('id','name','province')) then raise exception 'ข้อมูลสถานศึกษาไม่ถูกต้อง';end if;
 if operation='create' then
  if school_data ? 'id' then raise exception 'รหัสสถานศึกษาสร้างอัตโนมัติ';end if;
 else
  select * into current_row from public.schools where id=(school_data->>'id')::integer for update;
  if not found then raise exception 'ไม่พบสถานศึกษา';end if;
  if expected_revision is null or current_row.revision<>expected_revision then raise exception 'ข้อมูลสถานศึกษาถูกเปลี่ยนแปลง กรุณาโหลดใหม่' using errcode='40001';end if;
 end if;
 if operation in ('create','update') then
  if nullif(trim(school_data->>'name'),'') is null or length(school_data->>'name')>200 or nullif(trim(school_data->>'province'),'') is null or length(school_data->>'province')>100 then raise exception 'กรุณาระบุชื่อสถานศึกษาและจังหวัดให้ครบ';end if;
  if exists(select 1 from public.schools where lower(trim(name))=lower(trim(school_data->>'name')) and id is distinct from current_row.id) then raise exception 'ชื่อสถานศึกษาซ้ำ';end if;
 end if;
 -- Serialize creates with duplicate names, independently of IDs.
 if operation='create' then
  perform pg_advisory_xact_lock(hashtext('hr-schools'));
  if exists(select 1 from public.schools where lower(trim(name))=lower(trim(school_data->>'name'))) then raise exception 'ชื่อสถานศึกษาซ้ำ';end if;
  insert into public.schools(name,province) values(trim(school_data->>'name'),trim(school_data->>'province')) returning * into next_row;
 elsif operation='update' then
  update public.schools set name=trim(school_data->>'name'),province=trim(school_data->>'province'),revision=revision+1 where id=current_row.id returning * into next_row;
 elsif operation in ('deactivate','activate') then
  if current_row.is_active=(operation='activate') then raise exception 'สถานะสถานศึกษาไม่ได้เปลี่ยนแปลง';end if;
  update public.schools set is_active=(operation='activate'),revision=revision+1 where id=current_row.id returning * into next_row;
 else
  if exists(select 1 from public.personnel where school_id=current_row.id) or exists(select 1 from public.school_assignments where school_id=current_row.id) then raise exception 'มีบุคลากรหรือสิทธิ์อ้างอิง กรุณาปิดใช้งานแทนการลบ';end if;
  delete from public.schools where id=current_row.id;
 end if;
 result=case when operation='delete' then jsonb_build_object('id',current_row.id,'deleted',true) else to_jsonb(next_row) end;
 insert into public.administration_changes(entity,record_id,action,old_data,new_data,reason,actor_id)
 values('schools',coalesce(next_row.id,current_row.id)::text,upper(operation),coalesce(to_jsonb(current_row),'{}'::jsonb),result,trim(reason),auth.uid());
 return result;
end $$;
create or replace function public.manage_school(operation text,school_data jsonb,expected_revision integer default null,reason text default '')
returns jsonb language sql security invoker set search_path='' as $$select hr_private.school_manage(operation,school_data,expected_revision,reason)$$;

create or replace function hr_private.assignment_manage(assignment_data jsonb,expected_revision integer,remove_assignment boolean,reason text)
returns jsonb language plpgsql security definer set search_path='' as $$
declare target public.profiles; existing public.school_assignments; next_row public.school_assignments;
 selected_ids uuid[]; selected_permissions text[]; school integer; target_user uuid; new_role text;
begin
 if not public.is_admin() then raise exception 'เฉพาะผู้ดูแลระบบ' using errcode='42501';end if;
 if reason is null or length(trim(reason)) not between 5 and 1000 then raise exception 'กรุณาระบุเหตุผล 5–1,000 ตัวอักษร';end if;
 if jsonb_typeof(assignment_data) is distinct from 'object' or exists(select 1 from jsonb_object_keys(assignment_data) k where k not in ('user_id','school_id','permissions','personnel_ids')) then raise exception 'ข้อมูลสิทธิ์ไม่ถูกต้อง';end if;
 target_user=(assignment_data->>'user_id')::uuid;school=(assignment_data->>'school_id')::integer;
 select * into target from public.profiles where id=target_user for update;
 if not found or target.role='admin' or not exists(select 1 from public.personnel where user_id=target_user and deleted_at is null) then raise exception 'ต้องเลือกบัญชีบุคลากรที่ผูกกับทะเบียนใช้งานอยู่';end if;
 perform 1 from public.schools where id=school and (is_active or remove_assignment) for share;
 if not found then raise exception 'สถานศึกษาไม่พร้อมใช้งาน';end if;
 select * into existing from public.school_assignments where user_id=target_user and school_id=school for update;
 if found then
  if expected_revision is null or existing.revision<>expected_revision then raise exception 'สิทธิ์ถูกเปลี่ยนแปลง กรุณาโหลดใหม่' using errcode='40001';end if;
 elsif expected_revision is not null or remove_assignment then raise exception 'ไม่พบสิทธิ์เดิม กรุณาโหลดใหม่' using errcode='40001';end if;
 if remove_assignment then
  delete from public.school_assignments where id=existing.id;
 else
  if jsonb_typeof(assignment_data->'permissions') is distinct from 'array' then raise exception 'สิทธิ์ต้องเป็นรายการ';end if;
  select array_agg(value) into selected_permissions from jsonb_array_elements_text(assignment_data->'permissions');
  if selected_permissions is null or not(selected_permissions @> array['view']) or not(selected_permissions <@ array['view','create_personnel','personnel_write','education_write','certificates_write','documents_write','import','request_delete']) or cardinality(selected_permissions)<>(select count(distinct x) from unnest(selected_permissions) x) then raise exception 'รายการสิทธิ์ไม่ถูกต้อง';end if;
  if assignment_data->'personnel_ids' is null or assignment_data->'personnel_ids'='null'::jsonb then selected_ids=null;
  else
   if jsonb_typeof(assignment_data->'personnel_ids') is distinct from 'array' then raise exception 'รายชื่อผู้รับผิดชอบไม่ถูกต้อง';end if;
   select array_agg(value::uuid) into selected_ids from jsonb_array_elements_text(assignment_data->'personnel_ids');
   if selected_ids is null or cardinality(selected_ids)<>(select count(distinct x) from unnest(selected_ids) x) or exists(select 1 from unnest(selected_ids) x where not exists(select 1 from public.personnel p where p.id=x and p.school_id=school and p.deleted_at is null)) then raise exception 'ต้องเลือกรายชื่อในสถานศึกษาที่กำหนด';end if;
   if selected_permissions && array['create_personnel','import'] then raise exception 'เพิ่มบุคลากรและนำเข้า Excel ต้องใช้ขอบเขตทั้งสถานศึกษา';end if;
  end if;
  if 'import'=any(selected_permissions) and not(selected_permissions @> array['create_personnel','personnel_write']) then raise exception 'นำเข้า Excel ต้องมีสิทธิ์เพิ่มและแก้ไขทะเบียน';end if;
  insert into public.school_assignments(user_id,school_id,permissions,personnel_ids) values(target_user,school,selected_permissions,selected_ids)
   on conflict(user_id,school_id) do update set permissions=excluded.permissions,personnel_ids=excluded.personnel_ids,revision=public.school_assignments.revision+1,updated_at=clock_timestamp() returning * into next_row;
 end if;
 new_role=case when exists(select 1 from public.school_assignments where user_id=target_user) then 'school_editor' else 'personnel' end;
 update public.profiles set role=new_role,account_revision=account_revision+1,sessions_revoked_before=clock_timestamp() where id=target_user;
 insert into public.administration_changes(entity,record_id,action,old_data,new_data,reason,actor_id)
 values('school_assignments',coalesce(next_row.id,existing.id)::text,case when remove_assignment then 'REVOKE' else 'GRANT' end,coalesce(to_jsonb(existing),'{}'::jsonb),coalesce(to_jsonb(next_row),'{}'::jsonb),trim(reason),auth.uid());
 return jsonb_build_object('ok',true,'role',new_role,'revision',next_row.revision,'sign_in_again',true);
end $$;
